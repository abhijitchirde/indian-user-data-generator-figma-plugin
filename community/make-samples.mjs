// Writes community/src/samples.js: real output of the plugin's own generators, used by the
// cover and slides so the images never show hand-typed data.
//
//   node community/make-samples.mjs
//
// Compiles src/fields.ts (and what it imports) with the project's TypeScript into a temp
// folder, then generates a few complete users. Run it again for a fresh set of people.

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "iudg-samples-"));

const tsc = path.join(root, "node_modules", "typescript", "bin", "tsc");
execFileSync(process.execPath, [
  tsc,
  path.join(root, "src", "fields.ts"),
  "--outDir", tmp,
  "--module", "commonjs",
  "--target", "es2020",
  "--esModuleInterop",
  "--skipLibCheck",
], { stdio: "inherit" });

const require = createRequire(import.meta.url);
const { FIELDS, Person } = require(path.join(tmp, "fields.js"));
const { GROUPS, PROFESSION_DOMAINS } = require(path.join(tmp, "fieldMeta.js"));

const COUNT = 8;
const people = Array.from({ length: COUNT }, () => {
  const person = new Person({ profDomain: "Random" });
  return Object.fromEntries(FIELDS.map((f) => [f.key, person.get(f.key)]));
});

const fields = FIELDS.map(({ key, label, shortLabel, group, inTable }) => ({
  key, label, shortLabel, group, inTable,
}));

const out = `// Generated by community/make-samples.mjs from the plugin's own generators. Don't edit by hand.
window.SAMPLES = ${JSON.stringify({ groups: GROUPS, domains: PROFESSION_DOMAINS, fields, people }, null, 2)};
`;
fs.writeFileSync(path.join(here, "src", "samples.js"), out);
fs.rmSync(tmp, { recursive: true, force: true });
console.log(`✓ community/src/samples.js: ${COUNT} users × ${fields.length} fields`);
